#!/usr/bin/env python3
"""
QMK OLED Image Converter for 128x32 displays.

Usage:
    # Generate placeholder images for all layers:
    python3 convert_image.py --generate-placeholders

    # Convert a single image to a C array:
    python3 convert_image.py my_image.png --name my_logo

    # Convert an image and append to existing header:
    python3 convert_image.py my_image.png --name my_logo --append

Notes:
    - Input images are resized to 128x32 and converted to monochrome
    - White pixels = OFF, Black pixels = ON (standard OLED convention)
    - Output is a PROGMEM byte array for use with oled_write_raw_P()
"""

import argparse
import sys
import os

from PIL import Image, ImageDraw, ImageFont


WIDTH = 128
HEIGHT = 32
HEADER_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "oled_images.h")


def image_to_bytes(img):
    """Convert a PIL Image (128x32, mode '1') to QMK OLED byte array.

    QMK OLED format: each byte is a vertical column of 8 pixels.
    Bit 0 = top pixel of the 8px column, bit 7 = bottom.
    Bytes go left-to-right across each 8px-tall "page", then next page.
    """
    img = img.convert("1")  # 1-bit monochrome
    pixels = img.load()
    result = []

    for page in range(HEIGHT // 8):  # 4 pages for 32px tall
        for col in range(WIDTH):      # 128 columns
            byte = 0
            for bit in range(8):
                y = page * 8 + bit
                if pixels[col, y] == 0:  # black pixel = ON
                    byte |= (1 << bit)
            result.append(byte)

    return result


def bytes_to_c_array(data, name):
    """Format byte array as a C PROGMEM constant."""
    lines = []
    lines.append(f"static const char PROGMEM {name}[] = {{")
    for i in range(0, len(data), 16):
        chunk = data[i:i+16]
        hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(f"    {hex_str},")
    lines.append("};")
    return "\n".join(lines)


def create_text_image(text, subtitle=None):
    """Create a 128x32 image with centered text."""
    img = Image.new("1", (WIDTH, HEIGHT), color=1)  # white background
    draw = ImageDraw.Draw(img)

    # Try to use a clean font, fall back to default
    try:
        font = ImageFont.truetype("/System/Library/Fonts/Menlo.ttc", 20)
        small_font = ImageFont.truetype("/System/Library/Fonts/Menlo.ttc", 10)
    except (IOError, OSError):
        try:
            font = ImageFont.truetype("/System/Library/Fonts/Helvetica.ttc", 20)
            small_font = ImageFont.truetype("/System/Library/Fonts/Helvetica.ttc", 10)
        except (IOError, OSError):
            font = ImageFont.load_default()
            small_font = font

    # Draw main text centered
    bbox = draw.textbbox((0, 0), text, font=font)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]

    if subtitle:
        y_offset = -4
    else:
        y_offset = 0

    x = (WIDTH - tw) // 2
    y = (HEIGHT - th) // 2 + y_offset - bbox[1]
    draw.text((x, y), text, fill=0, font=font)  # black text

    # Draw subtitle if provided
    if subtitle:
        bbox2 = draw.textbbox((0, 0), subtitle, font=small_font)
        tw2 = bbox2[2] - bbox2[0]
        x2 = (WIDTH - tw2) // 2
        draw.text((x2, 24), subtitle, fill=0, font=small_font)

    return img


def create_placeholder_image():
    """Create a simple placeholder frame for the right side."""
    img = Image.new("1", (WIDTH, HEIGHT), color=1)
    draw = ImageDraw.Draw(img)

    # Draw border
    draw.rectangle([0, 0, WIDTH-1, HEIGHT-1], outline=0)
    draw.rectangle([2, 2, WIDTH-3, HEIGHT-3], outline=0)

    # Draw centered text
    try:
        font = ImageFont.truetype("/System/Library/Fonts/Menlo.ttc", 10)
    except (IOError, OSError):
        font = ImageFont.load_default()

    text = "Sofia"
    bbox = draw.textbbox((0, 0), text, font=font)
    tw = bbox[2] - bbox[0]
    th = bbox[3] - bbox[1]
    x = (WIDTH - tw) // 2
    y = (HEIGHT - th) // 2 - bbox[1]
    draw.text((x, y), text, fill=0, font=font)

    return img


def generate_placeholders():
    """Generate placeholder images for all layers and the right-side logo."""
    layers = [
        ("base_img",     "BASE",     None),
        ("symbols_img",  "SYMBOLS",  None),
        ("numbers_img",  "NUMBERS",  None),
        ("nav_img",      "NAV",      None),
        ("setting_img",  "SETTING",  None),
    ]

    arrays = []
    arrays.append("#pragma once")
    arrays.append("")
    arrays.append("// OLED images for 128x32 display (512 bytes each)")
    arrays.append("// Generated by convert_image.py — replace with your own art!")
    arrays.append("// Re-run: python3 convert_image.py --generate-placeholders")
    arrays.append("")

    for name, text, subtitle in layers:
        img = create_text_image(text, subtitle)
        data = image_to_bytes(img)
        arrays.append(f"// Layer: {text}")
        arrays.append(bytes_to_c_array(data, name))
        arrays.append("")

        # Also save as PNG for reference
        png_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "oled_pngs")
        os.makedirs(png_dir, exist_ok=True)
        img.save(os.path.join(png_dir, f"{name}.png"))

    # Right-side placeholder
    img = create_placeholder_image()
    data = image_to_bytes(img)
    arrays.append("// Right side display")
    arrays.append(bytes_to_c_array(data, "logo_img"))
    arrays.append("")

    img.save(os.path.join(png_dir, "logo_img.png"))

    content = "\n".join(arrays)
    with open(HEADER_FILE, "w") as f:
        f.write(content)

    print(f"Generated {HEADER_FILE}")
    print(f"Reference PNGs saved to {png_dir}/")
    print(f"  Layer images: base_img.png, symbols_img.png, numbers_img.png, nav_img.png, setting_img.png")
    print(f"  Logo image:   logo_img.png")
    print()
    print("To replace an image:")
    print("  1. Create a 128x32 pixel image (black = lit pixels, white = off)")
    print("  2. Run: python3 convert_image.py your_image.png --name base_img")
    print("  3. Copy the output array into oled_images.h")


def convert_single_image(image_path, name):
    """Convert a single image file to a C array."""
    img = Image.open(image_path)
    img = img.resize((WIDTH, HEIGHT), Image.LANCZOS)
    img = img.convert("1")  # monochrome

    data = image_to_bytes(img)
    print(bytes_to_c_array(data, name))
    print()
    print(f"// Converted from: {image_path} ({WIDTH}x{HEIGHT})")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="QMK OLED image converter for 128x32 displays")
    parser.add_argument("image", nargs="?", help="Image file to convert")
    parser.add_argument("--name", default="custom_img", help="C variable name (default: custom_img)")
    parser.add_argument("--generate-placeholders", action="store_true", help="Generate placeholder images for all layers")

    args = parser.parse_args()

    if args.generate_placeholders:
        generate_placeholders()
    elif args.image:
        convert_single_image(args.image, args.name)
    else:
        parser.print_help()
